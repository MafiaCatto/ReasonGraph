import { Decision, AnalysisResult } from "./types";

/**
 * Generates an executive decision memo in clean GitHub-flavored Markdown.
 */
export function generateMarkdownBrief(decision: Decision, analysis: AnalysisResult): string {
  const { leader, runnerUp, margin, rankings, breakEvens, insights } = analysis;
  const dateStr = new Date().toISOString().split("T")[0];

  let md = `# Decision Brief: ${decision.title}\n\n`;
  md += `**Date:** ${dateStr}  \n`;
  md += `**Confidence Rating:** ${decision.confidence}% (${decision.confidence < 65 ? "Speculative / Low Observation" : "High Confidence / Validated Data"})  \n`;
  if (decision.context) {
    md += `**Context:** ${decision.context}  \n`;
  }
  md += `\n---\n\n`;

  // Executive Summary
  md += `## 1. Executive Verdict\n\n`;
  if (leader) {
    md += `**Current Recommendation:** **${leader.name}** (Weighted Score: **${leader.rawTotal} / 10**)\n\n`;
    if (runnerUp) {
      md += `* **Margin to Runner-Up:** +${margin.toFixed(2)} pts over *${runnerUp.name}* (${runnerUp.rawTotal}/10).\n`;
      md += `* **Lead Robustness:** ${
        margin < 0.6
          ? "⚠️ **Fragile** (Functional tie; sensitive to a single score variance)"
          : margin < 1.4
          ? "⚖️ **Moderate** (Survives modest changes, but verify top assumptions)"
          : "🛡️ **Robust** (Clear mathematical lead under current priorities)"
      }\n`;
    }
  }

  // Decision Matrix Table
  md += `\n## 2. Decision Matrix & Weighted Scores\n\n`;
  md += `| Option | ` + decision.criteria.map((c) => `${c.name} (${c.weight}%)`).join(" | ") + ` | Weighted Total | Rank |\n`;
  md += `| :--- | ` + decision.criteria.map(() => `:---:`).join(" | ") + ` | :---: | :---: |\n`;

  for (const row of rankings) {
    const scores = decision.criteria.map((c) => row.scores[c.id] ?? "-").join(" | ");
    md += `| **${row.name}** | ${scores} | **${row.rawTotal}** | #${row.rank} |\n`;
  }

  // Sensitivity Analysis
  if (runnerUp) {
    md += `\n## 3. Dynamic Sensitivity Matrix & Multi-Metric Fragility\n\n`;

    if (analysis.multiMetric) {
      const mm = analysis.multiMetric;
      md += `* **Multi-Metric Hyperplane Distance:** \`${mm.euclideanDistance}\` (${mm.resilienceLevel.replace("_", " ")})\n`;
      md += `* **Simultaneous Drift Budget:** A collective drift of **±${mm.averageShiftNeeded} pts** across ${mm.favorableMetricsCount} metrics overturns the leader.\n`;
      md += `* **Systemic Assessment:** ${mm.interpretation}\n\n`;
    }

    if (analysis.sensitivityGrid && analysis.sensitivityGrid.length > 0) {
      md += `### Criteria Pivot Points (#1 vs Top Contenders)\n\n`;
      md += `| Criterion | Weight | #1 ${leader?.name ?? "Leader"} | #2 ${runnerUp.name} | Δ to Flip (#1 vs #2) | Risk Status |\n`;
      md += `| :--- | :---: | :---: | :---: | :---: | :---: |\n`;
      for (const row of analysis.sensitivityGrid) {
        const deltaStr = row.runnerUpAdvantage
          ? "**Leader Trailing**"
          : row.runnerUpFeasible
          ? `+${row.runnerUpDelta} pts`
          : ">10 (Infeasible)";
        const statusStr =
          row.riskStatus === "CRITICAL_DOWN"
            ? "🔥 Trailing"
            : row.riskStatus === "SPOF_HIGH"
            ? "⚠️ High SPOF"
            : row.riskStatus === "MODERATE"
            ? "🟡 Moderate"
            : "🟢 Resilient";

        md += `| **${row.criterionName}** | ${row.weight}% | ${row.leaderScore} | ${row.runnerUpScore} | ${deltaStr} | ${statusStr} |\n`;
      }
      md += `\n`;
    }
  }

  // Red Team Review
  if (insights.length > 0) {
    md += `\n## 4. Red Team & Assumption Stress-Test\n\n`;
    for (const ins of insights) {
      const icon = ins.severity === "high" ? "🚨" : ins.severity === "medium" ? "⚠️" : "💡";
      md += `### ${icon} ${ins.title}\n`;
      md += `${ins.detail}\n\n`;
      md += `> **Action:** ${ins.recommendation}\n\n`;
    }
  }

  // Monte Carlo Probabilistic Simulation
  if (analysis.monteCarlo && analysis.monteCarlo.options.length > 0) {
    const mc = analysis.monteCarlo;
    md += `\n## 5. Monte Carlo Probabilistic Simulation (${mc.iterations.toLocaleString()} Iterations)\n\n`;
    md += `*Beta-PERT distribution modeling simulated under ${decision.confidence}% epistemic certainty:*\n\n`;
    md += `| Option | Win Probability | Expected (Mean) | Volatility (StdDev) | P10 (Bear Case) | P50 (Median) | P90 (Bull Case) | VaR 95% (Downside) |\n`;
    md += `| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |\n`;
    for (const opt of mc.options) {
      md += `| **${opt.optionName}** | **${opt.winProbability}%** | ${opt.mean} | ±${opt.stdDev} | ${opt.p10} | ${opt.p50} | ${opt.p90} | **${opt.var95}** |\n`;
    }
    md += `\n> **Summary:** ${mc.summaryText}\n\n`;
  }

  md += `---\n*Generated by ReasonGraph — Local-First Decision Intelligence Workbench.*\n`;
  return md;
}
